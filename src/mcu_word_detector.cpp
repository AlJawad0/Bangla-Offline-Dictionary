// ---------------------------------------------------------------------------

int OtsuThreshold(const uint32_t* histogram, int bins) {
  uint64_t total = 0;
  uint64_t sum = 0;
  for (int i = 0; i < bins; ++i) {
    total += histogram[i];
    sum += static_cast<uint64_t>(i) * histogram[i];
  }
  if (total == 0) return 0;

  uint64_t weight_background = 0;
  uint64_t sum_background = 0;
  uint64_t best_variance = 0;
  int best_threshold = 0;
  for (int t = 0; t < bins; ++t) {
    weight_background += histogram[t];
    sum_background += static_cast<uint64_t>(t) * histogram[t];
    if (weight_background == 0) continue;
    const uint64_t weight_foreground = total - weight_background;
    if (weight_foreground == 0) break;
    // sum_b*Wf - (sum-sum_b)*Wb == Wb*Wf*(mean_b - mean_f).
    const uint64_t left = sum_background * weight_foreground;
    const uint64_t right = (sum - sum_background) * weight_background;
    const uint64_t difference = left > right ? left - right : right - left;
    // Scale before squaring so the product cannot overflow 64 bits. The
    // between-class variance is only ever compared against itself.
    const uint64_t scaled = difference >> 10;
    const uint64_t variance = (scaled * scaled) / (weight_background * weight_foreground);
    if (variance > best_variance) {
      best_variance = variance;
      best_threshold = t;
    }
  }
  return best_threshold;
}

