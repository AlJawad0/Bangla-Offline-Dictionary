// The background is smooth by construction, so estimating it on a decimated
// image and bilinearly expanding it is visually identical to the full
// resolution blur while costing dec^2 times fewer multiply-accumulates. That
// saving is what makes a large, text-size-adaptive background window
// affordable on the MCU.
void DecimateBoxAverage(const uint8_t* gray, int width, int height, int dec, uint8_t* small,
                        int small_width, int small_height) {
  for (int j = 0; j < small_height; ++j) {
    const int y0 = j * dec;
    const int y1 = std::min(y0 + dec, height);
    for (int i = 0; i < small_width; ++i) {
      const int x0 = i * dec;
      const int x1 = std::min(x0 + dec, width);
      uint32_t sum = 0;
      uint32_t samples = 0;
      for (int y = y0; y < y1; ++y) {
        const uint8_t* row = gray + static_cast<size_t>(y) * width;
        for (int x = x0; x < x1; ++x) {
          sum += row[x];
          ++samples;
        }
      }
      small[static_cast<size_t>(j) * small_width + i] =
          samples == 0 ? 255 : static_cast<uint8_t>(sum / samples);
    }
  }
}

void BlurSmallSeparable(uint8_t* small, int width, int height, uint16_t* scratch_q8,
                        const uint16_t* kernel, int radius) {
  const int taps = 2 * radius + 1;
  for (int y = 0; y < height; ++y) {
    const uint8_t* row = small + static_cast<size_t>(y) * width;
    uint16_t* out = scratch_q8 + static_cast<size_t>(y) * width;
    for (int x = 0; x < width; ++x) {
      uint32_t acc_q15 = 0;
      for (int i = 0; i < taps; ++i) {
        acc_q15 += static_cast<uint32_t>(row[ClampIndex(x + i - radius, width - 1)]) * kernel[i];
      }
      out[x] = static_cast<uint16_t>((acc_q15 + 64U) >> 7);  // Q8
    }
  }
  for (int y = 0; y < height; ++y) {
    for (int x = 0; x < width; ++x) {
      uint32_t acc_q23 = 0;
      for (int i = 0; i < taps; ++i) {
        const int sy = ClampIndex(y + i - radius, height - 1);
        acc_q23 +=
            static_cast<uint32_t>(scratch_q8[static_cast<size_t>(sy) * width + x]) * kernel[i];
      }
      const uint32_t q8 = (acc_q23 + (1U << 14)) >> 15;
      small[static_cast<size_t>(y) * width + x] =
          static_cast<uint8_t>(std::min<uint32_t>(q8 >> 8, 255U));
    }
  }
}

// Bilinear expansion coordinate of full-resolution index `p` on a grid whose
// sample j represents the block centred at full-resolution j*dec + (dec-1)/2.
inline int32_t ExpandCoordQ16(int p, int dec, int small_extent) {
  int32_t q16 = (static_cast<int32_t>(2 * p - (dec - 1)) * 32768) / dec;
  const int32_t high = static_cast<int32_t>(small_extent - 1) << 16;
  if (q16 < 0) q16 = 0;
  if (q16 > high) q16 = high;
  return q16;
}

bool BuildInkMask(const uint8_t* gray, uint8_t* ink, uint8_t* background_small,
                  uint16_t* scratch_q8, int width, int height, int dec, int full_radius,
                  uint8_t threshold_c, int32_t* coord_x_q16, int32_t* coord_y_q16) {
  const int small_width = CeilDivPositive(width, dec);
  const int small_height = CeilDivPositive(height, dec);
  const int small_radius = ClampInt(CeilDivPositive(full_radius, dec), 2, kMaxKernelRadius);
  const uint32_t sigma_q12 =
      std::max<uint32_t>(4096U, (static_cast<uint32_t>(small_radius) * 4096U) / 2U);

  uint16_t kernel[kMaxKernelTaps];
  if (!GaussianKernelQ15(sigma_q12, small_radius, kernel)) return false;

  DecimateBoxAverage(gray, width, height, dec, background_small, small_width, small_height);
  BlurSmallSeparable(background_small, small_width, small_height, scratch_q8, kernel,
                     small_radius);

  for (int x = 0; x < width; ++x) coord_x_q16[x] = ExpandCoordQ16(x, dec, small_width);
  for (int y = 0; y < height; ++y) coord_y_q16[y] = ExpandCoordQ16(y, dec, small_height);

  const int32_t threshold_q16 = static_cast<int32_t>(threshold_c) << 16;
  for (int y = 0; y < height; ++y) {
    const int32_t fy = coord_y_q16[y];
    const int j0 = fy >> 16;
    const int j1 = std::min(j0 + 1, small_height - 1);
    const uint32_t wy = static_cast<uint32_t>(fy & 0xFFFF);
    const uint32_t iwy = 65536U - wy;
    const uint8_t* top = background_small + static_cast<size_t>(j0) * small_width;
    const uint8_t* bottom = background_small + static_cast<size_t>(j1) * small_width;
    const uint8_t* gray_row = gray + static_cast<size_t>(y) * width;
    uint8_t* ink_row = ink + static_cast<size_t>(y) * width;

    for (int x = 0; x < width; ++x) {
      const int32_t fx = coord_x_q16[x];
      const int i0 = fx >> 16;
      const int i1 = std::min(i0 + 1, small_width - 1);
      const uint32_t wx = static_cast<uint32_t>(fx & 0xFFFF);
      const uint32_t iwx = 65536U - wx;

      const uint64_t upper =
          static_cast<uint64_t>(top[i0]) * iwx + static_cast<uint64_t>(top[i1]) * wx;
      const uint64_t lower =
          static_cast<uint64_t>(bottom[i0]) * iwx + static_cast<uint64_t>(bottom[i1]) * wx;
      const int32_t background_q16 = static_cast<int32_t>((upper * iwy + lower * wy) >> 16);
      const int32_t gray_q16 = static_cast<int32_t>(gray_row[x]) << 16;
      ink_row[x] =
          (background_q16 > threshold_q16 && gray_q16 < background_q16 - threshold_q16) ? 1 : 0;
    }
  }
  return true;
}

