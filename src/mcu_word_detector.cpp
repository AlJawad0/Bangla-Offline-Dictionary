// Connected components
// ---------------------------------------------------------------------------

void EraseComponent(uint8_t* mask, int width, int height, uint32_t seed, uint32_t* stack,
                    size_t stack_capacity) {
  if (mask[seed] == 0) return;
  size_t stack_size = 0;
  stack[stack_size++] = seed;
  mask[seed] = 0;
  while (stack_size > 0) {
    const uint32_t index = stack[--stack_size];
    const int y = static_cast<int>(index) / width;
    const int x = static_cast<int>(index) - y * width;
    const int ny[4] = {y + 1, y - 1, y, y};
    const int nx[4] = {x, x, x + 1, x - 1};
    for (int n = 0; n < 4; ++n) {
      if (nx[n] < 0 || nx[n] >= width || ny[n] < 0 || ny[n] >= height) continue;
      const uint32_t neighbor = static_cast<uint32_t>(ny[n] * width + nx[n]);
      if (mask[neighbor] == 0) continue;
      mask[neighbor] = 0;
      if (stack_size < stack_capacity) stack[stack_size++] = neighbor;
    }
  }
}

struct CharPassResult {
  size_t count;
  size_t height_count;
  bool overflow;
  bool box_overflow;
};

// `work` is a destroyable copy of `ink`. Components smaller than the minimum
// character area are erased from `ink` immediately, so speckle noise cannot
// seed spurious word blobs during the merge.
CharPassResult CollectCharComponents(uint8_t* work, uint8_t* ink, int width, int height,
                                     uint32_t min_area, uint32_t* stack, size_t stack_capacity,
                                     CharBox* boxes, size_t box_capacity,
                                     uint32_t* height_histogram, size_t height_histogram_size) {
  CharPassResult out{0, 0, false, false};
  const size_t pixel_count = static_cast<size_t>(width) * height;

  for (size_t seed = 0; seed < pixel_count; ++seed) {
    if (work[seed] == 0) continue;

    size_t stack_size = 0;
    stack[stack_size++] = static_cast<uint32_t>(seed);
    work[seed] = 0;
    uint32_t area = 0;
    int min_x = width;
    int min_y = height;
    int max_x = 0;
    int max_y = 0;
    bool component_overflow = false;

    while (stack_size > 0) {
      const uint32_t index = stack[--stack_size];
      const int y = static_cast<int>(index) / width;
      const int x = static_cast<int>(index) - y * width;
      ++area;
      min_x = std::min(min_x, x);
      max_x = std::max(max_x, x);
      min_y = std::min(min_y, y);
      max_y = std::max(max_y, y);

      const int ny[4] = {y + 1, y - 1, y, y};
      const int nx[4] = {x, x, x + 1, x - 1};
      for (int n = 0; n < 4; ++n) {
        if (nx[n] < 0 || nx[n] >= width || ny[n] < 0 || ny[n] >= height) continue;
        const uint32_t neighbor = static_cast<uint32_t>(ny[n] * width + nx[n]);
        if (work[neighbor] == 0) continue;
        work[neighbor] = 0;
        if (stack_size < stack_capacity) {
          stack[stack_size++] = neighbor;
        } else {
          component_overflow = true;
        }
      }
    }

    if (component_overflow) {
      out.overflow = true;
      continue;
    }
    if (area < min_area) {
      EraseComponent(ink, width, height, static_cast<uint32_t>(seed), stack, stack_capacity);
      continue;
    }

    const size_t component_height = static_cast<size_t>(max_y - min_y + 1);
    if (component_height < height_histogram_size) {
      ++height_histogram[component_height];
      ++out.height_count;
    }
    if (out.count < box_capacity) {
      boxes[out.count++] =
          CharBox{static_cast<uint16_t>(min_x), static_cast<uint16_t>(min_y),
                  static_cast<uint16_t>(max_x), static_cast<uint16_t>(max_y), area,
                  static_cast<uint32_t>(seed)};
    } else {
      out.box_overflow = true;
    }
  }
  return out;
}

struct BlobBox {
  uint16_t x1;
  uint16_t y1;
  uint16_t x2;
  uint16_t y2;
  uint32_t area;
};

size_t CollectBlobs(uint8_t* mask, int width, int height, uint32_t min_area, uint32_t* stack,
                    size_t stack_capacity, BlobBox* boxes, size_t box_capacity,
                    bool* overflowed, bool* capacity_reached) {
  size_t count = 0;
  const size_t pixel_count = static_cast<size_t>(width) * height;

  for (size_t seed = 0; seed < pixel_count; ++seed) {
    if (mask[seed] == 0) continue;

    size_t stack_size = 0;
    stack[stack_size++] = static_cast<uint32_t>(seed);
    mask[seed] = 0;
    uint32_t area = 0;
    int min_x = width;
    int min_y = height;
    int max_x = 0;
    int max_y = 0;
    bool component_overflow = false;

    while (stack_size > 0) {
      const uint32_t index = stack[--stack_size];
      const int y = static_cast<int>(index) / width;
      const int x = static_cast<int>(index) - y * width;
      ++area;
      min_x = std::min(min_x, x);
      max_x = std::max(max_x, x);
      min_y = std::min(min_y, y);
      max_y = std::max(max_y, y);

      const int ny[4] = {y + 1, y - 1, y, y};
      const int nx[4] = {x, x, x + 1, x - 1};
      for (int n = 0; n < 4; ++n) {
        if (nx[n] < 0 || nx[n] >= width || ny[n] < 0 || ny[n] >= height) continue;
        const uint32_t neighbor = static_cast<uint32_t>(ny[n] * width + nx[n]);
        if (mask[neighbor] == 0) continue;
        mask[neighbor] = 0;
        if (stack_size < stack_capacity) {
          stack[stack_size++] = neighbor;
        } else {
          component_overflow = true;
        }
      }
    }

    if (component_overflow) {
      *overflowed = true;
      continue;
    }
    if (area < min_area) continue;
    if (count >= box_capacity) {
      *capacity_reached = true;
      continue;
    }
    boxes[count++] = BlobBox{static_cast<uint16_t>(min_x), static_cast<uint16_t>(min_y),
                             static_cast<uint16_t>(max_x), static_cast<uint16_t>(max_y), area};
  }
  return count;
}

uint16_t MedianHeightX2FromHistogram(const uint32_t* histogram, size_t histogram_size,
                                     size_t count) {
  if (histogram == nullptr || count == 0) return 0;
  const size_t rank_lo = (count - 1) / 2;
  const size_t rank_hi = count / 2;
  size_t seen = 0;
  uint16_t value_lo = 0;
  uint16_t value_hi = 0;
  bool have_lo = false;
  for (size_t h = 0; h < histogram_size; ++h) {
    const size_t next = seen + histogram[h];
    if (!have_lo && rank_lo < next) {
      value_lo = static_cast<uint16_t>(h);
      have_lo = true;
    }
    if (rank_hi < next) {
      value_hi = static_cast<uint16_t>(h);
      break;
    }
    seen = next;
  }
  return static_cast<uint16_t>(value_lo + value_hi);
}

// ---------------------------------------------------------------------------
// Skew estimation
// ---------------------------------------------------------------------------

// Handheld capture is never perfectly level. The anisotropic merge blur is only
// ~0.12*h tall, so a few degrees of tilt pull the far end of a long word out of
// the vertical support and split it. Measuring the baseline slope from
// neighbouring character centres lets the merge follow the text line instead.
int16_t EstimateSkewSlopeQ12(CharBox* boxes, size_t count, int char_height) {
  if (count < 8 || char_height <= 0) return 0;

  // Sorting by x bounds the right-neighbour search to a small window.
  std::sort(boxes, boxes + count, [](const CharBox& a, const CharBox& b) {
    const int ax = CharCenterX(a);
    const int bx = CharCenterX(b);
    if (ax != bx) return ax < bx;
    return a.y1 < b.y1;
  });

  const int max_dx = 3 * char_height;
  const int max_dy = std::max(2, (6 * char_height) / 10);
  // Slope histogram over [-0.1875, +0.1875] in steps of 1/512 (Q12 step 8).
  constexpr int kSlopeBins = 193;
  constexpr int kSlopeCenter = 96;
  uint16_t histogram[kSlopeBins] = {};
  uint32_t samples = 0;

  const size_t stride = count > 1200 ? (count / 1200) + 1 : 1;
  for (size_t i = 0; i < count; i += stride) {
    const int cx = CharCenterX(boxes[i]);
    const int cy = CharCenterY(boxes[i]);
    for (size_t j = i + 1; j < count; ++j) {
      const int dx = CharCenterX(boxes[j]) - cx;
      if (dx <= 0) continue;
      if (dx > max_dx) break;
      const int dy = CharCenterY(boxes[j]) - cy;
      if (dy > max_dy || dy < -max_dy) continue;
      const int slope_q12 = (dy * 4096) / dx;
      const int bin = kSlopeCenter + ((slope_q12 + (slope_q12 >= 0 ? 4 : -4)) / 8);
      if (bin >= 0 && bin < kSlopeBins) {
        ++histogram[bin];
        ++samples;
      }
      break;  // nearest right neighbour only
    }
  }

  if (samples < 8) return 0;
  const uint32_t rank = samples / 2;
  uint32_t seen = 0;
  int median_bin = kSlopeCenter;
  for (int b = 0; b < kSlopeBins; ++b) {
    seen += histogram[b];
    if (seen > rank) {
      median_bin = b;
      break;
    }
  }
  return static_cast<int16_t>(ClampInt((median_bin - kSlopeCenter) * 8, -737, 737));
}

