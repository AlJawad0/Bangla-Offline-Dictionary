// Stage 1: contrast measurement and adaptive threshold offset
// ---------------------------------------------------------------------------

// The fixed THRESH_C=12 of the original port assumes a well exposed page. A
// blurry, low contrast camera frame can have an ink-to-paper delta barely above
// 12, in which case the whole frame thresholds to nothing. Scaling the offset
// with the measured contrast keeps faint frames detectable while still
// rejecting sensor noise on crisp, high contrast frames.
uint8_t MeasureContrastAndThresholdC(const uint8_t* gray, size_t count,
                                     uint16_t* contrast_out) {
  uint32_t histogram[256] = {};
  for (size_t i = 0; i < count; ++i) ++histogram[gray[i]];

  // Paper level: the dominant bright mode.
  uint32_t best_count = 0;
  int paper = 255;
  for (int v = 64; v < 256; ++v) {
    if (histogram[v] > best_count) {
      best_count = histogram[v];
      paper = v;
    }
  }

  // Ink level: the 1st percentile of the intensity distribution.
  const uint32_t target = std::max<uint32_t>(1U, static_cast<uint32_t>(count / 100U));
  uint32_t accumulated = 0;
  int ink = paper;
  for (int v = 0; v < 256; ++v) {
    accumulated += histogram[v];
    if (accumulated >= target) {
      ink = v;
      break;
    }
  }

  const int contrast = std::max(0, paper - ink);
  if (contrast_out != nullptr) *contrast_out = static_cast<uint16_t>(contrast);
  return static_cast<uint8_t>(ClampInt(contrast / 12, 6, 18));
}

