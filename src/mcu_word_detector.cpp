// Max-pool decimation of the ink mask. The merge result is only used to group
// characters, never to place a box edge, so it can run coarse.
void DecimateInkMax(const uint8_t* ink, int width, int height, int dec, uint8_t* small,
                    int small_width, int small_height) {
  for (int j = 0; j < small_height; ++j) {
    const int y0 = j * dec;
    const int y1 = std::min(y0 + dec, height);
    uint8_t* out = small + static_cast<size_t>(j) * small_width;
    for (int i = 0; i < small_width; ++i) {
      const int x0 = i * dec;
      const int x1 = std::min(x0 + dec, width);
      uint8_t value = 0;
      for (int y = y0; y < y1 && !value; ++y) {
        const uint8_t* row = ink + static_cast<size_t>(y) * width;
        for (int x = x0; x < x1; ++x) {
          if (row[x]) {
            value = 1;
            break;
          }
        }
      }
      out[i] = value;
    }
  }
}

// Horizontal pass of the anisotropic merge blur. The row index is sheared along
// the measured baseline so the elongated kernel axis follows the text rather
// than the pixel grid.
void MergeHorizontalPass(const uint8_t* ink, uint16_t* out_q15, int width, int height,
                         const uint16_t* kernel, int radius, const int16_t* tap_row_offset) {
  const int taps = 2 * radius + 1;
  for (int y = 0; y < height; ++y) {
    uint16_t* out = out_q15 + static_cast<size_t>(y) * width;
    for (int x = 0; x < width; ++x) {
      uint32_t acc_q15 = 0;
      for (int i = 0; i < taps; ++i) {
        const int sx = ClampIndex(x + i - radius, width - 1);
        const int sy = ClampIndex(y + tap_row_offset[i], height - 1);
        if (ink[static_cast<size_t>(sy) * width + sx]) acc_q15 += kernel[i];
      }
      out[x] = static_cast<uint16_t>(std::min<uint32_t>(acc_q15, kQ15One));
    }
  }
}

inline uint16_t MergeVerticalAt(const uint16_t* horizontal, int width, int height, int x, int y,
                                const uint16_t* kernel, int radius) {
  const int taps = 2 * radius + 1;
  // Max is 32768 * 32768 = 1,073,741,824, so uint32 is safe.
  uint32_t acc_q30 = 0;
  for (int i = 0; i < taps; ++i) {
    const int sy = ClampIndex(y + i - radius, height - 1);
    acc_q30 += static_cast<uint32_t>(horizontal[static_cast<size_t>(sy) * width + x]) * kernel[i];
  }
  const uint32_t q15 = (acc_q30 + (1U << 14)) >> 15;
  return static_cast<uint16_t>(std::min<uint32_t>(q15, kQ15One));
}

// Builds the binary word mask in `map`.
//
// Two changes relative to the original port:
//   * the blurred response is written once into `map` instead of being computed
//     twice, once to find the peak and once to threshold;
//   * the threshold is a fraction of a per-text-line peak instead of the single
//     global frame peak. Under a global peak, one bold heading anywhere in the
//     frame raises the bar for every other line, which both drops faint lines
//     entirely and pulls the surviving contours inwards - a direct cause of
//     over-tight boxes.
bool BuildWordMask(const uint8_t* ink, uint8_t* map, uint16_t* horizontal, int width,
                   int height, uint16_t median_height_x2, int16_t slope_q12,
                   const DetectorConfig& config, uint16_t* row_peak) {
  const uint32_t pct_x = std::max<uint32_t>(1U, config.merge_sigma_x_pct);
  const uint32_t pct_y = std::max<uint32_t>(1U, config.merge_sigma_y_pct);
  const uint32_t sigma_x_q12 = std::max<uint32_t>(
      4096U, (static_cast<uint32_t>(median_height_x2) * pct_x * 2048U + 50U) / 100U);
  const uint32_t sigma_y_q12 = std::max<uint32_t>(
      2458U, (static_cast<uint32_t>(median_height_x2) * pct_y * 2048U + 50U) / 100U);

  const int radius_x = RadiusForSigmaQ12(sigma_x_q12, 3);
  const int radius_y = RadiusForSigmaQ12(sigma_y_q12, 2);
  if (radius_x > kMaxKernelRadius || radius_y > kMaxKernelRadius) return false;

  uint16_t kernel_x[kMaxKernelTaps];
  uint16_t kernel_y[kMaxKernelTaps];
  if (!GaussianKernelQ15(sigma_x_q12, radius_x, kernel_x) ||
      !GaussianKernelQ15(sigma_y_q12, radius_y, kernel_y)) {
    return false;
  }

  int16_t tap_row_offset[kMaxKernelTaps];
  for (int i = 0; i < 2 * radius_x + 1; ++i) {
    const int dx = i - radius_x;
    const int32_t shifted = static_cast<int32_t>(slope_q12) * dx;
    // Round to nearest, symmetric about zero, without relying on >> of negatives.
    tap_row_offset[i] = static_cast<int16_t>((shifted + (shifted >= 0 ? 2048 : -2048)) / 4096);
  }

  MergeHorizontalPass(ink, horizontal, width, height, kernel_x, radius_x, tap_row_offset);

  uint16_t global_peak = 0;
  for (int y = 0; y < height; ++y) {
    uint8_t* row = map + static_cast<size_t>(y) * width;
    uint16_t peak = 0;
    for (int x = 0; x < width; ++x) {
      const uint16_t value_q15 =
          MergeVerticalAt(horizontal, width, height, x, y, kernel_y, radius_y);
      // Q15 -> 8 bit. A 1/256 quantisation of full scale is far finer than a
      // 35% threshold needs.
      const uint8_t value_u8 = static_cast<uint8_t>(value_q15 >> 7);
      row[x] = value_u8;
      if (value_u8 > peak) peak = value_u8;
    }
    row_peak[y] = peak;
    if (peak > global_peak) global_peak = peak;
  }

  if (global_peak == 0) {
    std::memset(map, 0, static_cast<size_t>(width) * height);
    return true;
  }

  // Dilate the row peaks vertically so a whole text line shares one reference
  // level, then floor them at a quarter of the frame peak so blank rows cannot
  // amplify noise into a word.
  const int peak_window = radius_y + std::max(1, static_cast<int>(median_height_x2) / 4);
  const uint16_t floor_peak = static_cast<uint16_t>(global_peak / 4);
  const uint32_t threshold_pct = std::max<uint32_t>(1U, config.word_threshold_pct);
  for (int y = 0; y < height; ++y) {
    const int y0 = std::max(0, y - peak_window);
    const int y1 = std::min(height - 1, y + peak_window);
    uint16_t peak = 0;
    for (int s = y0; s <= y1; ++s) peak = std::max(peak, row_peak[s]);
    const uint32_t reference = std::max(peak, floor_peak);
    uint8_t* row = map + static_cast<size_t>(y) * width;
    for (int x = 0; x < width; ++x) {
      row[x] = (static_cast<uint32_t>(row[x]) * 100U > reference * threshold_pct) ? 1 : 0;
    }
  }
  return true;
}

