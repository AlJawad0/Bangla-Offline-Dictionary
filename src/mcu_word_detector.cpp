inline int CharCenterY(const CharBox& b) { return (b.y1 + b.y2) >> 1; }

// ---------------------------------------------------------------------------
// Gaussian kernels (Q15 taps, Q12 sigma, integer only)
// ---------------------------------------------------------------------------

bool GaussianKernelQ15(uint32_t sigma_q12, int radius, uint16_t* kernel) {
  if (sigma_q12 == 0 || radius < 0 || radius > kMaxKernelRadius || kernel == nullptr) {
    return false;
  }
  const int taps = 2 * radius + 1;
  const uint64_t sigma2 = static_cast<uint64_t>(sigma_q12) * sigma_q12;
  uint32_t raw_sum = 0;

  for (int i = 0; i < taps; ++i) {
    const int x = i - radius;
    const uint64_t ax = static_cast<uint64_t>(x < 0 ? -x : x);
    const uint64_t x2 = ax * ax;
    // exp(-x^2 / (2 sigma^2)); the LUT index is t*1024 with t = x^2/(2 sigma^2).
    uint32_t lut_index = DivRoundNearestU64(x2 * 8589934592ULL, sigma2);
    if (lut_index > 4608U) lut_index = 4608U;
    kernel[i] = kExpNegQ15[lut_index];
    raw_sum += kernel[i];
  }
  if (raw_sum == 0) return false;

  uint32_t normalized_sum = 0;
  for (int i = 0; i < taps; ++i) {
    kernel[i] = static_cast<uint16_t>(
        DivRoundNearestU64(static_cast<uint64_t>(kernel[i]) * kQ15One, raw_sum));
    normalized_sum += kernel[i];
  }

  const int32_t correction =
      static_cast<int32_t>(kQ15One) - static_cast<int32_t>(normalized_sum);
  const int32_t fixed_center = static_cast<int32_t>(kernel[radius]) + correction;
  if (fixed_center < 0 || fixed_center > 65535) return false;
  kernel[radius] = static_cast<uint16_t>(fixed_center);
  return true;
}

inline int RadiusForSigmaQ12(uint32_t sigma_q12, int minimum) {
  const int radius = static_cast<int>((3U * sigma_q12 + 4095U) / 4096U);
  return std::max(minimum, radius);
}

